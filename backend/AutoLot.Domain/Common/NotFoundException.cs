namespace AutoLot.Domain.Common;

/// <summary>
/// «Такого немає» — спільний предок для винятків про ненайдену сутність.
///
/// З'явився заради одного: усі вони влаштовані однаково — код повідомлення
/// плюс ідентифікатор, який треба підставити в текст. Без предка кожен із
/// дев'яти нащадків перетворився б із однорядкового оголошення на повний
/// клас із тілом конструктора, і всі дев'ять тіл були б однакові.
///
/// На поведінку це не впливає: обробник винятків розрізняє їх за конкретним
/// типом, а не за спільним предком.
/// </summary>
public abstract class NotFoundException : Exception
{
    /// <param name="messageCode">Код тексту — саме він, а не готовий текст.</param>
    /// <param name="id">Що шукали. Підставиться в текст замість «{id}».</param>
    protected NotFoundException(string messageCode, object id)
        : base(messageCode)
    {
        this.With("id", id);
    }
}
