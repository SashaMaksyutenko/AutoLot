using AutoLot.Domain.Common;
using AutoLot.Domain.Enums;

namespace AutoLot.Domain.Listings;

/// <summary>
/// Один запис в історії ціни оголошення.
///
/// Навіщо це покупцеві. Ціна на класифайді — не факт, а позиція в переговорах,
/// і найкорисніше про неї знати не саме число, а те, як воно поводилося. Авто,
/// яке місяць стоїть без руху, і авто, яке за той самий місяць подешевшало
/// тричі, — дві дуже різні розмови з продавцем. Зараз цього не видно нікому,
/// хоча дані для цього в системі проходять повз.
///
/// Записи не редагують і не видаляють: історія, яку можна підчистити, нічого
/// не варта. Тому тут немає ані часу зміни, ані того, хто змінював, — лише
/// момент, коли ціна стала такою.
/// </summary>
public sealed class PriceChange : Entity
{
    public long ListingId { get; set; }

    public Listing Listing { get; set; } = null!;

    /// <summary>Ціна так, як її бачив покупець: у валюті оголошення.</summary>
    public decimal Price { get; set; }

    public Currency Currency { get; set; }

    /// <summary>
    /// Та сама сума в гривні на момент запису.
    ///
    /// Потрібна, бо валюту оголошення можна змінити, і без спільної одиниці
    /// «було 5000, стало 200000» виглядало б як подорожчання в сорок разів.
    /// Курс беремо на момент зміни й більше не чіпаємо: історія має показувати
    /// те, що відбувалося тоді, а не перерахунок за сьогоднішнім курсом.
    /// </summary>
    public decimal PriceUah { get; set; }

    public DateTimeOffset ChangedAt { get; set; }
}
