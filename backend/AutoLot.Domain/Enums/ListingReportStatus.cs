namespace AutoLot.Domain.Enums;

/// <summary>
/// Доля скарги. Три стани, а не два: «розглянуто» без поділу на слушну й
/// безпідставну не дало б змоги ні виміряти якість скарг, ні побачити, хто
/// шле їх пачками на конкурентів.
/// </summary>
public enum ListingReportStatus
{
    /// <summary>Чекає на розгляд модератора.</summary>
    Pending = 0,

    /// <summary>Скарга слушна: оголошення знято з публікації.</summary>
    Accepted = 1,

    /// <summary>Скаргу відхилено: порушення немає, оголошення лишається.</summary>
    Dismissed = 2,
}
