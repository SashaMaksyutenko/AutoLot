namespace AutoLot.Domain.Enums;

/// <summary>
/// За що скаржаться на оголошення.
///
/// Перелік короткий навмисно. Довгий список ніхто не читає — люди тиснуть
/// перший-ліпший пункт, і модератор отримує причину, яка нічого не пояснює.
/// Тут кожен варіант відповідає окремій дії модератора, а все інше йде
/// в <see cref="Other"/> з обов'язковим поясненням.
///
/// Назви для показу лежать у сід-файлі report-reasons.json — у коді лише
/// самі значення.
/// </summary>
public enum ListingReportReason
{
    /// <summary>Схоже на шахрайство: передоплата, «авто вже в дорозі», підозріло низька ціна.</summary>
    Fraud = 0,

    /// <summary>Характеристики не відповідають дійсності: пробіг, рік, стан.</summary>
    WrongInformation = 1,

    /// <summary>Авто вже продано, а оголошення висить.</summary>
    AlreadySold = 2,

    /// <summary>Те саме авто вже є в іншому оголошенні.</summary>
    Duplicate = 3,

    /// <summary>Образливий вміст або реклама, що не стосується продажу авто.</summary>
    Offensive = 4,

    /// <summary>Усе решта. Пояснення обов'язкове — інакше скарга нічого не варта.</summary>
    Other = 5,
}
