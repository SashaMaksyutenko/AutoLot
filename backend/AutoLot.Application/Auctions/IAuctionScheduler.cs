namespace AutoLot.Application.Auctions;

/// <summary>
/// Планує закриття торгів на конкретний час (SPEC §5).
///
/// Оголошено інтерфейсом, бо планувальник — це зовнішній механізм, і
/// сценаріям байдуже, чим саме він реалізований. У тестах на його місце
/// стає заглушка, яка просто запам'ятовує, що і на коли замовили.
/// </summary>
public interface IAuctionScheduler
{
    /// <summary>
    /// Замовляє закриття лота на вказаний час. Повторний виклик для того
    /// самого лота ПЕРЕПИСУЄ попереднє замовлення — саме так працює
    /// антиснайпінг: кожна ставка під кінець відсуває час, і задачу треба
    /// переставити, а не додати ще одну.
    /// </summary>
    Task ScheduleCloseAsync(
        long listingId,
        DateTimeOffset endsAt,
        CancellationToken cancellationToken = default);
}
