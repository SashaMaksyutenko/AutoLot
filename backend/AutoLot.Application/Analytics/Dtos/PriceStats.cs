namespace AutoLot.Application.Analytics.Dtos;

/// <summary>На якій вибірці порахували ціну.</summary>
public enum PriceBasis
{
    /// <summary>Та сама модель і той самий рік — найточніше порівняння.</summary>
    ModelAndYear = 0,

    /// <summary>
    /// Та сама модель, будь-який рік. Ширше й грубіше, але для рідкісних
    /// авто це єдине, що взагалі можна показати.
    /// </summary>
    Model = 1,
}

/// <summary>
/// Ціни на ринку по одній моделі.
///
/// Усі суми в гривні. Не з примхи: оголошення виставляють у трьох валютах, і
/// без спільної одиниці «середня ціна» була б сумою доларів із гривнями.
/// Саме для цього в оголошенні й живе окреме поле <c>PriceUah</c>.
/// </summary>
public sealed record PriceStats(
    /// <summary>
    /// Скільки оголошень у вибірці. Показуємо ЗАВЖДИ й поруч із самою
    /// цифрою: «середня по трьох» і «середня по трьохстах» — різні за
    /// вагою твердження, і приховати це число означало б збрехати.
    /// </summary>
    int Count,

    PriceBasis Basis,
    string MakeName,
    string ModelName,

    /// <summary>Рік, якщо вибірка саме по ньому. Порожній для всієї моделі.</summary>
    int? Year,

    /// <summary>
    /// Медіана — «типова» ціна. Головне число тут саме вона, а не середнє:
    /// одне оголошення з абсурдною ціною зсуває середнє на десятки відсотків,
    /// а медіану майже не чіпає.
    /// </summary>
    decimal Median,

    decimal Average,
    decimal Min,
    decimal Max);

/// <summary>
/// Ціна конкретного оголошення на тлі ринку.
/// </summary>
public sealed record PriceInsight(
    PriceStats Market,

    /// <summary>Ціна цього оголошення в гривні — щоб порівняння було з чим.</summary>
    decimal PriceUah,

    /// <summary>
    /// Наскільки відрізняється від медіани, у відсотках. Від'ємне — дешевше.
    /// Відсоток, а не різниця в грошах: він зрозумілий незалежно від того,
    /// йдеться про 5 тисяч чи про 50.
    /// </summary>
    int PercentFromMedian);
