/**
 * Завчасне підвантаження файлу сторінки.
 *
 * Відколи сторінки роз'їхалися по окремих файлах (див. App.tsx), перший
 * перехід на авто коштує ще одного походу в мережу. Тут ми цей похід
 * починаємо раніше — щойно курсор ліг на картку. Поки людина довезе його до
 * кнопки миші, файл здебільшого вже на місці, і перехід виглядає миттєвим.
 *
 * Ключове слово void перед import() каже: результат нам не потрібен, ми лише
 * просимо браузер покласти файл до себе в запас. Другий і подальші виклики
 * import() з тим самим шляхом мережею не ходять — браузер віддає вже
 * завантажене; прапорець нижче лише дозволяє не звертатися до нього щоразу.
 */

let listingAsked = false

export function prefetchListingPage(): void {
  if (listingAsked) return
  listingAsked = true

  /*
    Помилку глушимо навмисно й мовчки: це підготовка про запас, і якщо
    мережа підвела, нічого страшного не сталося — React.lazy спробує ще
    раз під час справжнього переходу. Без catch браузер поскаржився б у
    консоль на «необроблену відмову» там, де скаржитися нема на що.
  */
  void import('./pages/ListingPage').catch(() => {})
}
